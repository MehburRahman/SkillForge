import { test, expect } from '@playwright/test'

test('evolution readiness and saved model requests are available through the real API', async ({ page }) => {
  await page.goto('/#evolution')
  await expect(page.getByRole('heading', { name: 'Evolution readiness' })).toBeVisible()
  await page.getByLabel('Validation catalog').selectOption('problems')
  await expect(page.getByText(/Not ready: \d+\/20 new completed training runs/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Propose and validate' })).toBeDisabled()
  await page.screenshot({ path: 'test-results/evolution-readiness.png', fullPage: true })
  await page.goto('/#runs')
  await page.getByRole('button', { name: 'double-train', exact: true }).click()
  await page.getByRole('button', { name: 'Load saved model requests' }).click()
  await page.getByText('generator · analysis', { exact: true }).click()
  await expect(page.getByLabel('Model request', { exact: true }).first()).toContainText('problem analyzer')
  await expect(page.getByLabel('Model response', { exact: true }).first()).toContainText('problem_type')
})

test('solve streams through the real API, survives reload, and opens saved history', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('API connected')).toBeVisible()
  await page.screenshot({ path: 'test-results/solve-desktop.png', fullPage: true })
  await page.getByLabel('Problem statement').fill('Read two integers and print their sum.')
  await page.getByRole('button', { name: 'Start solve' }).click()
  await expect(page).toHaveURL(/#solve\//)
  await expect(page.getByText(/Analysing the problem|Generating tests|Generating a solution/).first()).toBeVisible()
  await page.reload()
  await expect(page.getByText('Solve completed')).toBeVisible()
  await expect(page.getByLabel('Verdict evidence').getByText('PASS', { exact: true })).toBeVisible()
  await expect(page.getByText(/not independent verification/)).toBeVisible()
  const savedUrl = page.url()
  const reopened = await page.context().newPage()
  await reopened.goto(savedUrl)
  await expect(reopened.getByText('Solve completed')).toBeVisible()
  await reopened.getByRole('tab', { name: /Runs/ }).click()
  await reopened.getByRole('tab', { name: /Solve/ }).click()
  await expect(reopened).toHaveURL(savedUrl)
  await expect(reopened.getByText('Solve completed')).toBeVisible()
  await reopened.close()
  await page.getByRole('button', { name: 'View saved run' }).click()
  await expect(page.getByRole('heading', { name: 'Solution history' })).toBeVisible()
  await expect(page.getByLabel('Candidate code', { exact: true })).toContainText('print(a + b)')
  await page.screenshot({ path: 'test-results/run-detail.png', fullPage: true })
  expect(errors).toEqual([])
})

