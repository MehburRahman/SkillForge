test('Scala HTTP mode submits without manually supplied tests', async ({ page }) => {
  let submitted: Record<string, unknown> | undefined
  await page.route('**/api/solves', async route => {
    submitted = route.request().postDataJSON()
    await route.fulfill({ status: 422, json: { detail: 'Submission reached the API' } })
  })
  await page.goto('/')
  await page.getByLabel('Problem statement').fill('Implement the specified Scala service.')
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('scala')
  await page.getByText('Run settings & tests').click()
  await page.getByLabel('Execution mode').selectOption('http')
  await expect(page.getByLabel(/HTTP scenarios/)).toBeVisible()
  await page.getByRole('button', { name: 'Start solve' }).click()
  await expect(page.getByRole('alert')).toContainText('Submission reached the API')
  expect(submitted).toMatchObject({ language: 'scala', execution_mode: 'http' })
  expect(submitted).not.toHaveProperty('tests')
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('python')
  await expect(page.getByLabel('Execution mode')).toHaveValue('stdio')
})
